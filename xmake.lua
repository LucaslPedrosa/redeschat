set_project("redeschat")
set_version("0.1.0")
set_languages("c++20")

package("qt6sql")
    set_base("qt6lib")
    set_kind("library")
    on_load(function (package)
        package:add("deps", "qt6core", {version = package:version_str()})
        package:data_set("libname", "Sql")
        package:base():script("load")(package)
    end)
package_end()

add_rules("mode.debug", "mode.release")
add_requires("qt6widgets 6.9.1", "qt6network 6.9.1", "qt6sql 6.9.1")

